"""
log.py — лёгкое логирование ошибок для диагностики аддона Anker.

Пишет ошибки в anker_debug.log внутри папки аддона. Используется для тихо
проглоченных исключений (except: pass), чтобы будущие проблемы находились
без необходимости просить пользователя воспроизводить их заново.
"""

import os


def log_error(context: str, exc: Exception) -> None:
    """
    Пишет ошибку в лог-файл внутри папки аддона — для будущей диагностики
    тихо проглоченных исключений, без необходимости просить пользователя
    воспроизводить проблему заново.
    """
    try:
        log_path = os.path.join(os.path.dirname(__file__), "anker_debug.log")
        with open(log_path, "a", encoding="utf-8") as f:
            f.write(f"[{context}] {type(exc).__name__}: {exc}\n")
    except Exception:
        pass  # логирование не должно само становиться источником падений
